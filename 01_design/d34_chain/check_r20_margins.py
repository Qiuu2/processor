# ── ⭐ 余量退化判别式(critic D3D4-r9 MAJOR-1 修法,⛔ 不违反"不给 dB 倍数"那条)──
#   critic 给的形式:|距离 − 判据线| / 判据线 < 5% ⇒ 距离已退化为判据线本身
#   ⭐ 而我改成一个**对称、无量纲、对两个方向都成立**的等价形式:
#        min(|实测|, |判据线|) / max(|实测|, |判据线|) < 5%
#     ⇒ 含义相同(两者差一个数量级以上 ⇒ 距离饱和到较大的那个,不再携带"离线多近"的信息),
#       而它 ⛔ 不依赖判据方向('<=' 与 '>=' 用同一条式子)。
#   ⇒ ⭐ 而它比原式多抓到两条(逐条代入见下),其中 EXP-3c / EXP-9a 正是本表 v1
#     已用【人工】标出的那两条 ⇒ **机械判别式复现了人工判断** ⇒ 互为佐证。
def degenerate(meas, lim):
    a, b = abs(meas), abs(lim)
    hi = max(a, b)
    return (hi > 0) and (min(a, b) / hi < 0.05)

print("\n" + "=" * 100)
print("⭐ 余量退化判别式:min(|实测|,|判据线|)/max(...) < 5% ⇒ 【距离已退化为判据线本身】")
print("   ⇒ 该行的【距离】不携带关于实测值的信息 ⇒ ⛔ 不得用于薄厚判断")
